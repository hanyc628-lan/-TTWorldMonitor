/**
 * 按层级检索赛事
 */
export function getTournamentsByTier(tier: string): Tournament[] {
  return ALL_TOURNAMENTS.filter((t) => t.tier === tier);
}

/**
 * 获取当前进行中的赛事
 */
export function getLiveTournaments(): Tournament[] {
  return ALL_TOURNAMENTS.filter((t) => t.status === 'live' || t.status === 'upcoming');
}

